export function artById(id) { return ART.find((a) => a.id === id); }

// Converts an artwork to engine cells + the list of palette keys used.
export function artToGrid(art) {
  const h = art.rows.length;
  const w = Math.max(...art.rows.map((r) => r.length));
  const keys = [];
  const cells = [];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = art.rows[y][x] || '.';
      if (ch === '.' || ch === ' ') { cells.push(-1); continue; }
      if (!PALETTE[ch]) throw new Error(`Unknown color '${ch}' in ${art.id}`);
      let k = keys.indexOf(ch);
      if (k < 0) { k = keys.length; keys.push(ch); }
      cells.push(k);
    }
  }
  return { w, h, cells, keys, colors: keys.map((k) => PALETTE[k].hex) };
}
