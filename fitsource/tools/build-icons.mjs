// Builds assets/js/icons.js: an SVG sprite of the Phosphor icons the site uses
// (MIT, https://phosphoricons.com). Run after adding a name below.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "../node_modules/@phosphor-icons/core/assets");

const ICONS = [
  "magnifying-glass", "upload-simple", "camera", "image", "clipboard-text", "heart", "heart:fill", "bell", "bell-ringing:fill",
  "share-network", "download-simple", "arrow-right", "arrow-up-right", "arrow-left", "x", "check", "sparkle", "scan", "crop", "tag",
  "storefront", "recycle", "clock", "trash", "sun", "moon", "info", "warning", "lightning", "link", "copy", "squares-four",
  "t-shirt", "receipt", "arrows-clockwise", "caret-down", "plus", "selection-plus", "shopping-bag", "seal-check", "fire",
  "trend-up", "globe", "lock-simple", "hand-tap", "cpu", "eye", "chart-line-up", "users-three", "megaphone",
  "whatsapp-logo", "coat-hanger", "trend-down", "chat-circle-dots", "gift", "ruler", "check-circle:fill",
];

let symbols = "";
for (const spec of ICONS) {
  const [name, weight = "regular"] = spec.split(":");
  const file = path.join(root, weight, weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`);
  const svg = fs.readFileSync(file, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const id = weight === "regular" ? name : `${name}-${weight}`;
  symbols += `<symbol id="i-${id}" viewBox="0 0 256 256">${inner}</symbol>`;
}

const out = `// Generated by tools/build-icons.mjs from Phosphor Icons (MIT). Do not edit by hand.
export const SPRITE = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols}</svg>`)};
`;
fs.writeFileSync(path.join(here, "../assets/js/icons.js"), out);
console.log(`icons.js: ${ICONS.length} icons`);
