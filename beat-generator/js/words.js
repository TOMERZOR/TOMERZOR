BG.Freestyle = class {
  constructor(extraWords = []) {
    this.extra = extraWords;
    this.useExtra = true;
    this.deck = [];
    this.current = null;
    this.next = null;
  }

  setExtra(words) { this.extra = words; this.deck = []; }

  draw() {
    if (!this.deck.length) {
      const pool = BG.WORDS.concat(this.useExtra ? this.extra.concat(this.extra) : []);
      this.deck = pool.slice().sort(() => Math.random() - 0.5);
    }
    let w = this.deck.pop();
    if (w === this.current && this.deck.length) w = this.deck.pop();
    return w;
  }

  advance() {
    this.current = this.next || this.draw();
    this.next = this.draw();
    return this.current;
  }
};
