const last = {};
export function pick(key) {
  const arr = LINES[key];
  if (!arr) return '';
  let n = Math.floor(Math.random() * arr.length);
  if (arr.length > 1 && n === last[key]) n = (n + 1) % arr.length;
  last[key] = n;
  return arr[n];
}

