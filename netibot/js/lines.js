// Adds the lines above to whoever exists in this copy of the cast.
function mergeExtraLines() {
  for (const ids of new Set([...Object.keys(EXTRA_LINES), ...Object.keys(MORE_LINES)])) {
    const p = Cast.get(ids);
    if (!p || p.extraMerged) continue;
    p.extraMerged = true;
    for (const more of [EXTRA_LINES[ids], MORE_LINES[ids]]) {
      if (!more) continue;
      if (more.lines) p.lines = [...(p.lines || []), ...more.lines];
      if (more.barks) p.barks = [...(p.barks || []), ...more.barks];
    }
  }
}
