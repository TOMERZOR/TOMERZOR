// Generates js/levels-data.js: every level is built, verified by the smart bot
// and difficulty-tuned against the random player. Run: node tools/build-levels.mjs [count]
import { writeFileSync } from 'node:fs';
import { levelSpec, makeLevel, encodeLevel } from '../js/levels.js';

const COUNT = Number(process.argv[2] || 180);
const out = [];
const t0 = Date.now();
const summary = { tutorial: [], normal: [], hard: [], super: [] };
for (let i = 1; i <= COUNT; i++) {
  const spec = levelSpec(i);
  const lv = makeLevel(spec);
  out.push(encodeLevel(lv));
  summary[lv.tag].push(lv.rand);
  if (i <= 40 || i % 20 === 0) {
    const sh = lv.lanes.flat().length;
    console.log(`L${i} ${lv.tag.padEnd(8)} ${lv.art.padEnd(11)} ${lv.w}x${lv.h} colors ${lv.keys.length} buckets ${sh} lanes ${lv.lanes.length} spots ${lv.slots} rand ${Math.round(lv.rand * 100)}% ticks ${lv.ticks}`);
  }
}
for (const [k, v] of Object.entries(summary)) if (v.length) console.log(k, 'avg random win', Math.round(v.reduce((a, b) => a + b, 0) / v.length * 100) + '%', 'n', v.length);
const body = '// Generated by tools/build-levels.mjs — do not edit by hand.\nexport const LEVEL_DATA = ' + JSON.stringify(out) + ';\n';
writeFileSync(new URL('../js/levels-data.js', import.meta.url), body);
console.log(`wrote ${COUNT} levels, ${(body.length / 1024).toFixed(0)} KB in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
