// How a combo is written on screen
export function comboText(seq) {
  const dir = { F: "קדימה+", D: "למטה+", B: "אחורה+" };
  const btn = { P: "סטירה", K: "בעיטה" };
  return seq.map((t) => (t.length > 1 ? dir[t[0]] : "") + btn[t[t.length - 1]]).join(" ← ");
}
